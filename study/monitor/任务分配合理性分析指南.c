/*
 * Q1: 监控任务本身占用多少资源？
 * A: 监控任务优先级20（最低），每5秒执行一次，占用极少资源
 * 
 * Q2: 为什么我的任务状态总是显示Delayed？
 * A: 说明任务大部分时间都在等待，这是正常的，表示任务在等待延时或信号量
 * 
 * Q3: CPU使用率显示0%正常吗？
 * A: 刚启动时正常，统计任务需要几秒钟才能计算出准确值
 * 
 * Q4: 堆栈使用率突然变高怎么办？
 * A: 可能是某个函数调用深度增加，或者中断嵌套，建议增加堆栈大小
 * 
 * Q5: 如何判断任务是否死锁？
 * A: 如果任务长期处于Pending状态，且信号量没有释放，可能是死锁
 */

