/*
 ******************************************************************************
 *                      第一部分：为什么要分析任务分配
 ******************************************************************************
 */

/*
 * 在uC/OS-III中，任务分配包括：
 * - 任务优先级设置
 * - 任务堆栈大小分配
 * - 任务执行周期设置
 * - 任务间同步机制
 * 
 * 不合理的任务分配会导致：
 * 1. 高优先级任务饿死低优先级任务
 * 2. 堆栈溢出导致系统崩溃
 * 3. 任务响应不及时
 * 4. CPU资源浪费
 * 
 * sys_monitor.c 提供了监控这些数据的功能
 */

/*
 ******************************************************************************
 *                      第二部分：关键监控指标说明
 ******************************************************************************
 */

/*
 * ==================== CPU使用率 ====================
 * 
 * 指标来源：OSStatTaskCPUUsage (在sys_monitor.c中通过SysMonitor_GetCPUUsage获取)
 * 
 * 正常范围：
 * - 空闲系统：5% - 20%
 * - 中等负载：20% - 60%
 * - 高负载：60% - 85%
 * - 过载：> 85%
 * 
 * 解读：
 * - CPU使用率过低：说明任务周期设置太长，或者任务数量太少，资源浪费
 * - CPU使用率过高：可能出现任务调度不及时，需要优化
 * - 峰值过高：某个任务占用CPU时间过长
 */

/*
 * ==================== 堆栈使用率 ====================
 * 
 * 指标来源：OSTaskStkChk() (在sys_monitor.c中通过SysMonitor_GetTaskStackUsage获取)
 * 
 * 正常范围：
 * - 安全：< 50%
 * - 警告：50% - 70%
 * - 危险：70% - 90%
 * - 极危险：> 90%
 * 
 * 解读：
 * - 堆栈使用率过高：可能导致堆栈溢出，系统崩溃
 * - 堆栈使用率过低：浪费RAM资源，可以适当减小堆栈大小
 * 
 * 注意：
 * - 中断可能使用当前任务的堆栈
 * - printf等函数会消耗大量堆栈
 * - 递归函数会快速消耗堆栈
 */

/*
 * ==================== 任务状态分布 ====================
 * 
 * 指标来源：p_tcb->TaskState (在sys_monitor.c中显示)
 * 
 * 状态类型：
 * - Ready：就绪，等待CPU
 * - Delayed：延时等待中
 * - Pending：等待信号量/互斥锁/消息队列
 * - PendTout：等待资源同时超时等待
 * - Suspend：被挂起
 * 
 * 解读：
 * - 多个任务长期处于Ready状态：说明优先级设置可能有问题
 * - 任务长期处于Pending状态：检查信号量是否正确释放
 * - 任务频繁在Ready和Delayed间切换：说明周期设置合理
 */

/*
 * ==================== 上下文切换次数 ====================
 * 
 * 指标来源：OSTaskCtxSwCtr (在sys_monitor.c中显示)
 * 
 * 解读：
 * - 切换次数过多：说明任务周期太短，或者任务数量太多
 * - 切换次数过少：说明任务可能陷入死循环，或者系统负载过低
 * 
 * 正常值参考（1秒）：
 * - 简单系统：100-500次
 * - 中等系统：500-2000次
 * - 复杂系统：2000-5000次
 * - 超过10000次：需要检查是否有任务频繁切换
 */

/*
 ******************************************************************************
 *                   第三部分：如何判断任务优先级是否合理
 ******************************************************************************
 */

/*
 * ==================== 优先级设计原则 ====================
 * 
 * 1. 中断响应任务 > 数据采集任务 > 数据处理任务 > 显示任务
 * 2. 实时性要求高的任务优先级高
 * 3. 执行时间短的任务可以适当提高优先级
 * 4. 避免优先级反转（使用互斥锁的优先级继承）
 * 
 * 在你的项目中，推荐优先级分配：
 * 
 * 优先级  任务                    说明
 * ----------------------------------------------------------------------------
 *   2     启动任务                初始化，创建其他任务后立即删除
 *   3     统计任务(OS自带)        uC/OS-III内部统计任务
 *   4     协议解析任务            UART数据接收，需要快速响应
 *   6     MPU6050读取任务         传感器数据采集，100Hz
 *   8     LCD显示任务             显示刷新，50ms周期
 *   9     MPU6050显示任务         串口输出，200ms周期
 *  15     协议处理任务            处理解析后的数据
 *  20     监控任务                系统监控，最低优先级
 * 
 * 注意：优先级数字越小，优先级越高（uC/OS-III）
 */

/*
 * ==================== 通过监控数据判断 ====================
 * 
 * 查看监控输出中的任务状态：
 * 
 * 正常情况：
 * Protocol_Task    512/2560(20%)   4  Ready
 * MPU6050_Read     256/1024(25%)   6  Delayed
 * LCD_Task         128/1024(12%)   8  Delayed
 * 
 * 问题情况1：低优先级任务总是Ready，高优先级任务占用太多CPU
 * Protocol_Task    512/2560(80%)   4  Ready
 * LCD_Task         128/1024(10%)   8  Ready  <-- 长期Ready，无法执行
 * 
 * 问题情况2：任务频繁在Ready和Delayed间切换（周期太短）
 * Protocol_Task    512/2560(20%)   4  Ready
 * Protocol_Task    512/2560(20%)   4  Delayed
 * Protocol_Task    512/2560(20%)   4  Ready
 * ...
 * 
 * 优化方法：
 * - 如果低优先级任务长期Ready：降低高优先级任务的执行频率
 * - 如果任务切换过于频繁：增加任务延时时间
 */

/*
 ******************************************************************************
 *                   第四部分：如何判断堆栈大小是否合理
 ******************************************************************************
 */

/*
 * ==================== 堆栈大小设计原则 ====================
 * 
 * 1. 中断处理使用当前任务的堆栈
 * 2. 函数调用深度越大，需要的堆栈越多
 * 3. printf等库函数消耗大量堆栈（200-500字节）
 * 4. 浮点运算消耗更多堆栈
 * 
 * 推荐堆栈大小：
 * 
 * 任务类型              最小堆栈    推荐堆栈    说明
 * ----------------------------------------------------------------------------
 * 简单任务（无printf）   256        512        简单循环，无复杂函数
 * 中等任务（少量printf） 512        1024       偶尔打印，中等复杂度
 * 复杂任务（频繁printf） 1024       2048       频繁打印，复杂处理
 * 协议解析任务          1024       2560       需要处理大量数据
 * 
 * 在你的项目中：
 * - Protocol_Task: 2560字节（推荐，使用printf较多）
 * - MPU6050_Read: 1024字节（合适）
 * - LCD_Task: 1024字节（合适）
 */

/*
 * ==================== 通过监控数据判断 ====================
 * 
 * 查看监控输出中的堆栈使用：
 * 
 * 正常情况：
 * Protocol_Task    512/2560(20%)   4  Ready
 *                   ↑    ↑   ↑
 *                   |    |   使用率20%（安全）
 *                   |    总大小2560字节
 *                   已使用512字节
 * 
 * 警告情况（需要增加堆栈）：
 * Protocol_Task    2304/2560(90%)   4  Ready
 *                               ↑
 *                               使用率90%（危险！）
 * 
 * 优化方法：
 * - 如果使用率 > 70%：增加堆栈大小
 * - 如果使用率 < 20%：可以适当减小堆栈大小，节省RAM
 * 
 * 注意：
 * - 堆栈使用率是动态变化的
 * - 中断发生时可能临时增加堆栈使用
 * - 建议保留至少30%的余量
 */

/*
 ******************************************************************************
 *                   第五部分：如何判断任务周期是否合理
 ******************************************************************************
 */

/*
 * ==================== 任务周期设计原则 ====================
 * 
 * 1. 数据采集任务周期 = 1 / 采样频率
 * 2. 显示刷新任务周期 >= 20ms（避免闪烁）
 * 3. 控制任务周期根据控制算法要求
 * 4. 后台任务周期可以较长（100ms-1000ms）
 * 
 * 在你的项目中：
 * 
 * 任务                当前周期    推荐周期    说明
 * ----------------------------------------------------------------------------
 * MPU6050_Read        10ms        10ms        100Hz采样，合适
 * LCD_Task            20ms        50ms        显示不需要太频繁
 * MPU6050_Display     200ms       200ms       串口输出，合适
 * Protocol_Task       无延时      有数据就处理  使用消息队列，合适
 * 
 * 优化建议：
 * - LCD_Task可以改为50ms，减少CPU占用
 * - 如果CPU使用率高，可以适当增加各任务周期
 */

/*
 * ==================== 通过监控数据判断 ====================
 * 
 * 查看CPU使用率和上下文切换次数：
 * 
 * [CPU Usage]
 *   Current: 85.50%    <-- CPU使用率过高！
 *   Peak:    95.20%
 *   Idle:    14.50%
 * 
 * [Context Switch Statistics]
 *   Total Context Switches: 1234567
 *   Context Switches/sec:   15000    <-- 切换次数过多！
 * 
 * 问题分析：
 * - CPU使用率85%：系统负载过高
 * - 切换次数15000次/秒：任务切换太频繁
 * 
 * 优化方法：
 * 1. 增加任务周期（特别是LCD_Task）
 * 2. 合并相似任务（如两个MPU6050显示任务）
 * 3. 使用事件驱动替代轮询
 * 
 * 修改示例：
 * // 原来
 * OSTimeDly(20, OS_OPT_TIME_DLY, &err);  // 50Hz
 * 
 * // 优化后
 * OSTimeDly(50, OS_OPT_TIME_DLY, &err);  // 20Hz，减少CPU占用
 */

