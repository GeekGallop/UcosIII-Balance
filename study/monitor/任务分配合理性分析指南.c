#include "sys_monitor.h"

void start_task(void *p_arg)
{
    OS_ERR err;
    
    /* ... 其他初始化 ... */
    
    /* 初始化系统监控 */
    if(SysMonitor_Init() != 0) {
        printf("Failed to init system monitor!\r\n");
    }
    
    /* 删除启动任务 */
    OSTaskDel(NULL, &err);
}

