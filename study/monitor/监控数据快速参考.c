/*
 * ==================== CPU使用率过高 ====================
 * 
 * 症状：Current > 80% 或 Peak > 90%
 * 
 * 操作步骤：
 * 1. 查看哪个任务占用CPU最多
 * 2. 增加该任务的延时时间
 * 3. 或者降低该任务的优先级
 * 4. 重新编译，再次监控
 * 
 * 代码修改示例：
 * // 原来
 * OSTimeDly(10, OS_OPT_TIME_DLY, &err);  // 100Hz
 * 
 * // 优化后
 * OSTimeDly(50, OS_OPT_TIME_DLY, &err);  // 20Hz，减少CPU占用
 */

/*
 * ==================== 堆栈使用率过高 ====================
 * 
 * 症状：某个任务堆栈使用率 > 70%
 * 
 * 操作步骤：
 * 1. 找到堆栈使用率高的任务
 * 2. 增加该任务的堆栈大小
 * 3. 重新编译，再次监控
 * 
 * 代码修改示例：
 * // 原来
 * #define PROTOCOL_STK_SIZE   1024
 * 
 * // 优化后
 * #define PROTOCOL_STK_SIZE   2048  // 增加一倍
 */

/*
 * ==================== 任务优先级不合理 ====================
 * 
 * 症状：低优先级任务长期Ready，高优先级任务CPU占用高
 * 
 * 操作步骤：
 * 1. 调整任务优先级
 * 2. 实时性要求高的任务优先级提高
 * 3. 后台任务优先级降低
 * 4. 重新编译，再次监控
 * 
 * 代码修改示例：
 * // 原来
 * #define PROTOCOL_PRIO       15  // 太低
 * 
 * // 优化后
 * #define PROTOCOL_PRIO       4   // 提高优先级
 */

/*
 * ==================== 任务切换过于频繁 ====================
 * 
 * 症状：Context Switches/sec > 10000
 * 
 * 操作步骤：
 * 1. 增加各任务的延时时间
 * 2. 合并相似任务
 * 3. 使用事件驱动替代轮询
 * 4. 重新编译，再次监控
 * 
 * 代码修改示例：
 * // 原来 - 多个短周期任务
 * Task1: OSTimeDly(10, ...);  // 100Hz
 * Task2: OSTimeDly(10, ...);  // 100Hz
 * Task3: OSTimeDly(10, ...);  // 100Hz
 * 
 * // 优化后 - 增加周期，减少切换
 * Task1: OSTimeDly(50, ...);  // 20Hz
 * Task2: OSTimeDly(50, ...);  // 20Hz
 * Task3: OSTimeDly(100, ...); // 10Hz
 */

