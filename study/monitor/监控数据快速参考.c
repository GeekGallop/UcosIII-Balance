/*
 * ==================== CPU使用率判断 ====================
 * 
 * 当前CPU使用率          状态        建议
 * ----------------------------------------------------------------------------
 * < 20%                 空闲        可以增加任务或提高频率
 * 20% - 60%             正常        保持现状
 * 60% - 80%             繁忙        考虑优化，增加任务周期
 * 80% - 95%             过载        必须优化，检查是否有死循环
 * > 95%                 危险        系统可能不稳定，立即检查
 * 
 * 峰值CPU使用率          状态        建议
 * ----------------------------------------------------------------------------
 * < 70%                 正常        系统有余量
 * 70% - 85%             警告        偶尔峰值，可以接受
 * > 85%                 危险        需要找出峰值原因并优化
 */

/*
 * ==================== 堆栈使用率判断 ====================
 * 
 * 堆栈使用率             状态        建议
 * ----------------------------------------------------------------------------
 * < 30%                 过低        可以减小堆栈，节省RAM
 * 30% - 50%             安全        理想状态
 * 50% - 70%             警告        注意观察，保留余量
 * 70% - 85%             危险        建议增加堆栈大小
 * > 85%                 极危险      必须增加堆栈，可能溢出
 * 
 * 注意：堆栈使用率是动态的，中断可能临时增加使用
 */

/*
 * ==================== 任务状态判断 ====================
 * 
 * 状态        含义                    是否正常
 * ----------------------------------------------------------------------------
 * Ready       就绪，等待CPU            正常（但长期Ready可能优先级有问题）
 * Delayed     延时等待中               正常
 * Pending     等待信号量/互斥锁        正常（但长期Pending可能死锁）
 * PendTout    等待+超时                正常
 * Suspend     被挂起                   正常（如果被故意挂起）
 * 
 * 异常情况：
 * - 低优先级任务长期Ready + 高优先级任务占用高CPU = 优先级需要调整
 * - 任务长期Pending（>10秒）= 可能死锁，检查信号量释放
 * - 任务频繁在Ready和Delayed间切换（每秒>100次）= 周期太短
 */

/*
 * ==================== 上下文切换判断 ====================
 * 
 * 切换次数/秒            状态        建议
 * ----------------------------------------------------------------------------
 * < 1000                过低        检查是否有任务死循环
 * 1000 - 5000           正常        一般系统
 * 5000 - 10000          偏高        任务较多，可以接受
 * > 10000               过高        任务切换太频繁，增加周期
 * 
 * 计算方法：
 * 切换次数/秒 = 总切换次数 / 运行时间(秒)
 */

